#!/usr/bin/env python3
"""Generate the Open Feedback feed and static session pages from the homepage agenda.

Run from any directory: python3 scripts/build_sessions.py [--check]
The agenda's data-session-id attributes are permanent feedback IDs.
"""

import argparse
from datetime import datetime
from html import escape
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import unicodedata
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = 'https://devfest26.gdglebanon.com'
DATE = '2026-11-28'
VOID = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr'}


class Node:
    def __init__(self, tag='', attrs=()):
        self.tag = tag
        self.attrs = dict(attrs)
        self.children = []

    def find_all(self, tag=None, css_class=None, id=None):
        found = []
        if ((tag is None or self.tag == tag)
                and (css_class is None or css_class in self.attrs.get('class', '').split())
                and (id is None or self.attrs.get('id') == id)):
            found.append(self)
        for child in self.children:
            if isinstance(child, Node):
                found.extend(child.find_all(tag, css_class, id))
        return found

    def text(self):
        return ''.join(c.text() if isinstance(c, Node) else c for c in self.children).strip()

    def html(self, prefix=''):
        attrs = self.attrs.copy()
        if attrs.get('src', '').startswith('assets/'):
            attrs['src'] = prefix + attrs['src']
        attributes = ''.join(f' {k}="{escape(v or "", quote=True)}"' for k, v in attrs.items())
        opening = f'<{self.tag}{attributes}>'
        if self.tag in VOID:
            return opening
        return opening + ''.join(c.html(prefix) if isinstance(c, Node) else escape(c) for c in self.children) + f'</{self.tag}>'


class Document(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.root = Node()
        self.stack = [self.root]
        self.feed(source)

    def handle_starttag(self, tag, attrs):
        node = Node(tag, attrs)
        self.stack[-1].children.append(node)
        if tag not in VOID:
            self.stack.append(node)

    def handle_endtag(self, tag):
        for index in range(len(self.stack) - 1, 0, -1):
            if self.stack[index].tag == tag:
                del self.stack[index:]
                break

    def handle_data(self, data):
        self.stack[-1].children.append(data)


def slug(value):
    ascii_name = unicodedata.normalize('NFKD', value).encode('ascii', 'ignore').decode().lower()
    return re.sub(r'[^a-z0-9]+', '-', ascii_name).strip('-')


def timestamp(clock):
    return datetime.fromisoformat(f'{DATE}T{clock}').replace(tzinfo=ZoneInfo('Asia/Beirut')).isoformat(timespec='seconds')


def time_label(clock):
    hours, minutes = map(int, clock.split(':'))
    return f'{hours % 12 or 12}:{minutes:02d} {"a.m." if hours < 12 else "p.m."}'


def shell(title, path, content, *, session=False):
    prefix = '../../' if session else '../'
    description = f'{title} — DevFest Beirut 2026, November 28 at MEA Conference Center. Session details and feedback.'
    scripts = (f'<script src="{prefix}assets/sessions/feedback-config.js" defer></script>\n'
               f'  <script src="{prefix}assets/sessions/feedback.js?v=5" defer></script>') if session else ''
    return f'''<!doctype html>
<!-- Generated by scripts/build_sessions.py; edit the homepage agenda, then regenerate. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="{escape(description, quote=True)}">
  <meta name="theme-color" content="#f1f5f9">
  <title>{escape(title)} | DevFest Beirut 2026</title>
  <link rel="canonical" href="{ORIGIN}{path}">
  <meta property="og:title" content="{escape(title, quote=True)} | DevFest Beirut 2026">
  <meta property="og:description" content="{escape(description, quote=True)}">
  <meta property="og:type" content="website">
  <meta property="og:url" content="{ORIGIN}{path}">
  <meta property="og:image" content="{ORIGIN}/assets/images/beirut-poster-2026.jpg">
  <link rel="icon" href="{prefix}assets/images/favicon-beirut.svg" type="image/svg+xml">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Google+Sans:wght@400;700&amp;family=Google+Sans+Code:wght@400;500;600;700&amp;display=swap" rel="stylesheet">
  <link rel="stylesheet" href="{prefix}style.css?v=22">
  <link rel="stylesheet" href="{prefix}assets/sessions/sessions.css?v=5">
{scripts}
</head>
<body class="session-page">
  <a class="skip-link" href="#main">Skip to content</a>
  <header class="session-header"><div class="container">
    <a class="session-brand" href="{prefix}index.html" aria-label="DevFest Beirut 2026 home"><img src="{prefix}assets/images/devfest-beirut-2026.svg" alt="DevFest Beirut 2026"></a>
    <nav aria-label="Session navigation"><a href="{prefix}index.html#agenda">Full agenda</a><a href="{prefix}sessions/">All sessions</a></nav>
  </div></header>
  <main id="main" class="container session-main">
{content}
  </main>
  <footer class="session-footer"><div class="container">DevFest Beirut 2026 · GDG Coast Lebanon · November 28, 2026</div></footer>
</body>
</html>
'''


def generate():
    doc = Document((ROOT / 'index.html').read_text()).root
    agenda = doc.find_all(id='agenda')[0]
    sessions, speakers, output, cards = {}, {}, {}, []
    for item in agenda.find_all(css_class='agenda-session'):
        session_id = item.attrs['data-session-id']
        if not re.fullmatch(r'[a-z0-9-]+', session_id) or session_id in sessions:
            raise ValueError(f'Invalid or duplicate session ID: {session_id}')
        title = item.find_all(tag='h3')[0].text()
        times = [n.attrs['datetime'] for n in item.find_all(tag='time')]
        start, end = times
        assert timestamp(end) > timestamp(start), title
        kinds = item.find_all(css_class='session-type')
        kind = kinds[0].text() if kinds else 'Break'
        location = item.find_all(css_class='session-location')[0].text()
        people = item.find_all(css_class='session-person')
        speaker_ids = []
        for person in people:
            name = person.find_all(tag='strong')[0].text()
            speaker_id = slug(name)
            speaker_ids.append(speaker_id)
            position = person.find_all(css_class='speaker-position')
            speakers[speaker_id] = {
                'id': speaker_id,
                'name': name,
                'photoUrl': f'{ORIGIN}/assets/feedback/speakers/{speaker_id}.svg',
                'company': position[0].text() if position else '',
                'socials': [],
            }
            # A neutral initials avatar is deliberate: the source images are full posters,
            # not standalone headshots. The website retains its existing portrait crops.
            initials = ''.join(word[0] for word in name.replace('Dr. ', '').split()[:2])
            output[f'assets/feedback/speakers/{speaker_id}.svg'] = (
                f'<svg xmlns="http://www.w3.org/2000/svg" width="160" height="160" viewBox="0 0 160 160" role="img" aria-label="{escape(name, quote=True)}">'
                f'<rect width="160" height="160" rx="80" fill="#e8f0fe"/>'
                f'<text x="80" y="80" dy=".35em" text-anchor="middle" font-family="Arial,sans-serif" font-size="50" font-weight="700" fill="#174ea6">{escape(initials)}</text></svg>\n')
        hidden = kind not in ('Talk', 'Panel discussion', 'Keynote')
        sessions[session_id] = {
            'id': session_id, 'title': title, 'speakers': speaker_ids, 'tags': [kind],
            'startTime': timestamp(start), 'endTime': timestamp(end),
            'trackTitle': location, 'hideInFeedback': hidden,
        }
        if hidden:
            continue
        path = f'/sessions/{session_id}/'
        participant_lists = item.find_all(css_class='session-people')
        notes = item.find_all(css_class='session-note')
        note = notes[0].text() if notes else ''
        if participant_lists:
            participant_heading = 'Speaker' if len(people) == 1 else 'Speakers &amp; moderator'
            participant_list = participant_lists[0].html('../../')
        else:
            participant_heading = 'About this session'
            participant_list = f'<p>{escape(note)}</p>'
        content = f'''    <span class="session-eyebrow">{escape(kind)} · {escape(session_id.upper())}</span>
    <h1>{escape(title)}</h1>
    <div class="session-meta"><span>Saturday, November 28, 2026</span><span><time datetime="{timestamp(start)}">{time_label(start)}</time> – <time datetime="{timestamp(end)}">{time_label(end)}</time> · Beirut time</span><span>{escape(location)}</span></div>
    <section class="session-content" aria-labelledby="participants-title"><h2 id="participants-title">{participant_heading}</h2>{participant_list}</section>
    <section class="session-feedback" data-session-feedback data-session-id="{session_id}" data-session-date="{DATE}" aria-labelledby="feedback-title">
      <h2 id="feedback-title">{'Rate keynote' if kind == 'Keynote' else 'Share your feedback'}</h2>
      <p>Let the speakers know what worked and what could be even better.</p>
      <p role="status">Loading session feedback…</p>
      <div data-feedback-form></div>
      <noscript><p>Enable JavaScript to load the feedback form.</p></noscript>
    </section>'''
        output[f'sessions/{session_id}/index.html'] = shell(title, path, content, session=True)
        names = ', '.join(speakers[key]['name'] for key in speaker_ids) or note
        action = 'Rate keynote' if kind == 'Keynote' else 'Session details &amp; feedback'
        cards.append(f'<li><a href="{session_id}/"><span class="session-eyebrow">{escape(kind)} · {time_label(start)}</span><h2>{escape(title)}</h2><p>{escape(names)}</p><span class="session-list-action">{action}</span></a></li>')
    assert sessions and speakers
    output['openfeedback.json'] = json.dumps({'sessions': sessions, 'speakers': speakers}, ensure_ascii=False, indent=2) + '\n'
    output['sessions/index.html'] = shell('Sessions & feedback', '/sessions/', f'''    <span class="session-eyebrow">DEVFEST BEIRUT 2026</span>
    <h1>Sessions &amp; feedback</h1>
    <p>Explore the talks and panels. Open a session to share your feedback.</p>
    <p>Saturday, November 28 · All times are local to Beirut. The agenda is subject to change.</p>
    <ol class="session-list">{''.join(cards)}</ol>''')
    urls = [ORIGIN + '/', ORIGIN + '/sessions/'] + [ORIGIN + f'/sessions/{key}/' for key, value in sessions.items() if not value['hideInFeedback']]
    output['sitemap.xml'] = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + ''.join(f'  <url><loc>{url}</loc></url>\n' for url in urls) + '</urlset>\n'
    return output, sessions, speakers


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated files are missing or outdated.')
    args = parser.parse_args()
    output, sessions, speakers = generate()
    stale = []
    for name, content in output.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, 'Regenerate session files: ' + ', '.join(stale) + '\n')
    print(f'{"Verified" if args.check else "Generated"} {len(sessions)} agenda entries, {sum(not s["hideInFeedback"] for s in sessions.values())} session pages, {len(speakers)} speakers.')


if __name__ == '__main__':
    main()
